#!/usr/bin/env bash
# Generates, from the migrations (not from a hosted project):
#   packages/database/src/database.types.ts     TypeScript types (same generator the Supabase CLI uses)
#   packages/validation/src/db-contract.generated.json   CHECK enums + varchar lengths for drift tests
# `--check` regenerates into a temp dir and fails if the committed files are stale (use in CI).
set -euo pipefail
# shellcheck source=local-db.sh
source "$(dirname "$0")/local-db.sh"

MODE="${1:-write}"
TYPES_FILE="$ROOT/packages/database/src/database.types.ts"
CONTRACT_FILE="$ROOT/packages/validation/src/db-contract.generated.json"
PG_META="$ROOT/packages/database/node_modules/@supabase/postgres-meta/dist/server/server.js"
[ -f "$PG_META" ] || { echo "run 'pnpm install' first" >&2; exit 1; }

start_local_db
OUT="$(mktemp -d)"
trap 'stop_local_db; rm -rf "$OUT"' EXIT

{
  echo "// GENERATED by supabase/scripts/gen-types.sh from supabase/migrations. Do not edit; run 'pnpm db:types'."
  PG_META_DB_URL="postgresql://postgres@localhost:$PORT/$LOCAL_DB_NAME?host=$WORK" \
  PG_META_GENERATE_TYPES=typescript PG_META_GENERATE_TYPES_INCLUDED_SCHEMAS=public \
    node "$PG_META"
} > "$OUT/database.types.ts"
lpsql "-At -f '$WORK/sql/schema-contract.sql'" > "$OUT/db-contract.generated.json"

if [ "$MODE" = "--check" ]; then
  status=0
  diff -u "$TYPES_FILE" "$OUT/database.types.ts" >&2 || status=1
  diff -u "$CONTRACT_FILE" "$OUT/db-contract.generated.json" >&2 || status=1
  [ "$status" = 0 ] && echo "generated files are up to date" || { echo "STALE: run 'pnpm db:types' and commit" >&2; exit 1; }
else
  mkdir -p "$(dirname "$TYPES_FILE")" "$(dirname "$CONTRACT_FILE")"
  cp "$OUT/database.types.ts" "$TYPES_FILE"
  cp "$OUT/db-contract.generated.json" "$CONTRACT_FILE"
  echo "wrote ${TYPES_FILE#"$ROOT"/} and ${CONTRACT_FILE#"$ROOT"/}"
fi
