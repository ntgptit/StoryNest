import {
  COLLABORATOR_ROLES,
  STORY_STATUS,
  STORY_STATUSES,
  VISIBILITIES,
  VISIBILITY,
  type StoryForm,
} from "@storynest/validation";
import { buildStorageKey } from "@storynest/utils";
import type { DataClient } from "../../_shared/client.ts";
import { AppError, toAppError, unwrap } from "../../_shared/errors.ts";
import type { PreparedImage } from "../../_shared/image-prepare.ts";
import { toStoryPayload, toStoryUpdate } from "../model/story-form.ts";
import type { StudioRole } from "../model/studio-story.ts";
import type { TagChip } from "../model/tags.ts";

export interface StoryForEdit {
  id: string;
  /** Values for the form. */
  form: StoryForm;
  role: StudioRole;
  deletedAt: string | null;
  /** The story's tags, by name. */
  tags: TagChip[];
  coverStorageKey: string | null;
}

const EDIT_COLUMNS =
  "id, owner_id, slug, title, synopsis, category_id, language_code, status, visibility, is_mature, deleted_at, cover_storage_key";

/**
 * Creates a story owned by `userId`. The id is generated by the caller (so a retry after a lost response cannot
 * create a second story: the same id hits the primary key). A taken (owner, slug) is an AppError `conflict` with the
 * unique-violation code. RLS also requires an active account.
 */
export async function createStory(client: DataClient, userId: string, id: string, form: StoryForm): Promise<string> {
  unwrap(await client.from("stories").insert({ id, owner_id: userId, ...toStoryPayload(form) }));
  return id;
}

/** Updates the story settings. Only the owner and co-authors may (RLS); zero matched rows is `notFound`. */
export async function updateStory(client: DataClient, storyId: string, form: StoryForm): Promise<void> {
  const rows = unwrap(await client.from("stories").update(toStoryUpdate(form)).eq("id", storyId).select("id"));
  if (!rows || rows.length === 0) throw new AppError("notFound", "Story not found or not editable");
}

/** Soft delete (deleted_at set) or restore (cleared). There is no hard delete: nothing ever loses data. */
export async function setStoryDeleted(client: DataClient, storyId: string, deleted: boolean): Promise<void> {
  const rows = unwrap(
    await client
      .from("stories")
      .update({ deleted_at: deleted ? new Date().toISOString() : null })
      .eq("id", storyId)
      .select("id"),
  );
  if (!rows || rows.length === 0) throw new AppError("notFound", "Story not found or not editable");
}

async function collaboratorRole(client: DataClient, userId: string, storyId: string): Promise<StudioRole | null> {
  const collaborator = unwrap(
    await client
      .from("story_collaborators")
      .select("collaborator_role")
      .eq("story_id", storyId)
      .eq("user_id", userId)
      .maybeSingle(),
  );
  return COLLABORATOR_ROLES.find((r) => r === collaborator?.collaborator_role) ?? null;
}

/** The story and the caller's role on it, or null when it does not exist or is not the caller's to open. */
export async function getStoryForEdit(
  client: DataClient,
  userId: string,
  storyId: string,
): Promise<StoryForEdit | null> {
  const row = unwrap(await client.from("stories").select(EDIT_COLUMNS).eq("id", storyId).maybeSingle());
  if (!row) return null;

  const role = row.owner_id === userId ? "owner" : await collaboratorRole(client, userId, storyId);
  // A moderator can read any story through RLS, but the studio only opens stories the user works on.
  if (role === null) return null;

  const tagRows =
    unwrap(await client.from("story_tags").select("tag:tags(slug, display_name)").eq("story_id", storyId)) ?? [];
  const tags = tagRows
    .flatMap((r) => (r.tag ? [{ slug: String(r.tag.slug), name: r.tag.display_name }] : []))
    .sort((a, b) => a.name.localeCompare(b.name));

  return {
    id: row.id,
    role,
    deletedAt: row.deleted_at,
    tags,
    coverStorageKey: row.cover_storage_key,
    form: {
      title: row.title,
      slug: row.slug,
      synopsis: row.synopsis,
      categoryId: row.category_id === null ? "" : String(row.category_id),
      languageCode: row.language_code,
      status: STORY_STATUSES.find((v) => v === row.status) ?? STORY_STATUS.DRAFT,
      visibility: VISIBILITIES.find((v) => v === row.visibility) ?? VISIBILITY.PRIVATE,
      isMature: row.is_mature,
    },
  };
}

export interface DeletedStory {
  id: string;
  title: string;
  deletedAt: string;
}

/** The caller's own soft-deleted stories, most recently deleted first (restore list). */
export async function listDeletedStories(client: DataClient, userId: string): Promise<DeletedStory[]> {
  const rows =
    unwrap(
      await client
        .from("stories")
        .select("id, title, deleted_at")
        .eq("owner_id", userId)
        .not("deleted_at", "is", null)
        .order("deleted_at", { ascending: false }),
    ) ?? [];
  return rows.flatMap((r) => (r.deleted_at ? [{ id: r.id, title: r.title, deletedAt: r.deleted_at }] : []));
}

/**
 * Replaces the story's tags by these names. The database cleans and merges them by slug, creates the unknown ones
 * (within a daily quota) and refuses bad input, a story that is not the caller's to tag, and too many tags.
 */
export async function setStoryTags(client: DataClient, storyId: string, names: readonly string[]): Promise<TagChip[]> {
  const rows = unwrap(await client.rpc("set_story_tags", { p_story_id: storyId, p_names: [...names] })) ?? [];
  return rows.map((r) => ({ slug: String(r.slug), name: r.display_name }));
}

export const COVERS_BUCKET = "covers";

function toStorageError(error: { message: string; statusCode?: string | number; status?: number }): AppError {
  // supabase-js reports Storage failures as { message, statusCode } (string) or { status }.
  const status = Number(error.statusCode ?? error.status);
  if (status === 401) return new AppError("unauthenticated", error.message, { cause: error });
  if (status === 403) return new AppError("forbidden", error.message, { cause: error });
  if (status === 400 || status === 413 || status === 415)
    return new AppError("invalid", error.message, { cause: error });
  return toAppError(error);
}

async function setCoverKey(client: DataClient, storyId: string, key: string | null): Promise<void> {
  const rows = unwrap(await client.from("stories").update({ cover_storage_key: key }).eq("id", storyId).select("id"));
  if (!rows || rows.length === 0) throw new AppError("notFound", "Story not found or not editable");
}

/**
 * Uploads a prepared picture into the story's folder and points the story at it. The name is generated, so a replaced
 * cover has a new address and caches never show the old one. If saving fails the uploaded object is removed; once the
 * story points at the new one the previous object is removed (best effort).
 */
export async function uploadCover(
  client: DataClient,
  story: { id: string; coverStorageKey: string | null },
  cover: PreparedImage,
): Promise<string> {
  const key = buildStorageKey(story.id, cover.extension);
  const bucket = client.storage.from(COVERS_BUCKET);
  const { error } = await bucket.upload(key, cover.blob, {
    contentType: cover.contentType,
    cacheControl: "31536000",
    upsert: false,
  });
  if (error !== null) throw toStorageError(error);
  try {
    await setCoverKey(client, story.id, key);
  } catch (failure) {
    await bucket.remove([key]).catch(() => undefined);
    throw failure;
  }
  if (story.coverStorageKey !== null) await bucket.remove([story.coverStorageKey]).catch(() => undefined);
  return key;
}

/** Clears the cover (the title's first letter shows again) and deletes the object. */
export async function removeCover(
  client: DataClient,
  story: { id: string; coverStorageKey: string | null },
): Promise<void> {
  await setCoverKey(client, story.id, null);
  if (story.coverStorageKey !== null) {
    await client.storage
      .from(COVERS_BUCKET)
      .remove([story.coverStorageKey])
      .catch(() => undefined);
  }
}
