import {
  COLLABORATOR_ROLES,
  STORY_STATUS,
  STORY_STATUSES,
  VISIBILITIES,
  VISIBILITY,
  type StoryForm,
} from "@storynest/validation";
import type { DataClient } from "../../_shared/client.ts";
import { AppError, unwrap } from "../../_shared/errors.ts";
import { toStoryPayload, toStoryUpdate } from "../model/story-form.ts";
import type { StudioRole } from "../model/studio-story.ts";

export interface StoryForEdit {
  id: string;
  /** Values for the form. */
  form: StoryForm;
  role: StudioRole;
  deletedAt: string | null;
}

const EDIT_COLUMNS =
  "id, owner_id, slug, title, synopsis, category_id, language_code, status, visibility, is_mature, deleted_at";

/**
 * Creates a story owned by `userId`. The id is generated by the caller (so a retry after a lost response cannot
 * create a second story: the same id hits the primary key). A taken (owner, slug) is an AppError `conflict` with the
 * unique-violation code. RLS also requires an active account.
 */
export async function createStory(client: DataClient, userId: string, id: string, form: StoryForm): Promise<string> {
  unwrap(await client.from("stories").insert({ id, owner_id: userId, ...toStoryPayload(form) }));
  return id;
}

/** Updates the story settings. Only the owner and co-authors may (RLS); zero matched rows is `notFound`. */
export async function updateStory(client: DataClient, storyId: string, form: StoryForm): Promise<void> {
  const rows = unwrap(await client.from("stories").update(toStoryUpdate(form)).eq("id", storyId).select("id"));
  if (!rows || rows.length === 0) throw new AppError("notFound", "Story not found or not editable");
}

/** Soft delete (deleted_at set) or restore (cleared). There is no hard delete: nothing ever loses data. */
export async function setStoryDeleted(client: DataClient, storyId: string, deleted: boolean): Promise<void> {
  const rows = unwrap(
    await client
      .from("stories")
      .update({ deleted_at: deleted ? new Date().toISOString() : null })
      .eq("id", storyId)
      .select("id"),
  );
  if (!rows || rows.length === 0) throw new AppError("notFound", "Story not found or not editable");
}

async function collaboratorRole(client: DataClient, userId: string, storyId: string): Promise<StudioRole | null> {
  const collaborator = unwrap(
    await client
      .from("story_collaborators")
      .select("collaborator_role")
      .eq("story_id", storyId)
      .eq("user_id", userId)
      .maybeSingle(),
  );
  return COLLABORATOR_ROLES.find((r) => r === collaborator?.collaborator_role) ?? null;
}

/** The story and the caller's role on it, or null when it does not exist or is not the caller's to open. */
export async function getStoryForEdit(
  client: DataClient,
  userId: string,
  storyId: string,
): Promise<StoryForEdit | null> {
  const row = unwrap(await client.from("stories").select(EDIT_COLUMNS).eq("id", storyId).maybeSingle());
  if (!row) return null;

  const role = row.owner_id === userId ? "owner" : await collaboratorRole(client, userId, storyId);
  // A moderator can read any story through RLS, but the studio only opens stories the user works on.
  if (role === null) return null;

  return {
    id: row.id,
    role,
    deletedAt: row.deleted_at,
    form: {
      title: row.title,
      slug: row.slug,
      synopsis: row.synopsis,
      categoryId: row.category_id === null ? "" : String(row.category_id),
      languageCode: row.language_code,
      status: STORY_STATUSES.find((v) => v === row.status) ?? STORY_STATUS.DRAFT,
      visibility: VISIBILITIES.find((v) => v === row.visibility) ?? VISIBILITY.PRIVATE,
      isMature: row.is_mature,
    },
  };
}

export interface DeletedStory {
  id: string;
  title: string;
  deletedAt: string;
}

/** The caller's own soft-deleted stories, most recently deleted first (restore list). */
export async function listDeletedStories(client: DataClient, userId: string): Promise<DeletedStory[]> {
  const rows =
    unwrap(
      await client
        .from("stories")
        .select("id, title, deleted_at")
        .eq("owner_id", userId)
        .not("deleted_at", "is", null)
        .order("deleted_at", { ascending: false }),
    ) ?? [];
  return rows.flatMap((r) => (r.deleted_at ? [{ id: r.id, title: r.title, deletedAt: r.deleted_at }] : []));
}
